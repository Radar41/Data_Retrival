function reqSet = build_fred_requirements(options)
%BUILD_FRED_REQUIREMENTS Requirement set for the FRED catalog, linked to its tests.
%
% reqSet = build_fred_requirements()
% reqSet = build_fred_requirements(OutputFile="requirements/fred_catalog.slreqx")
%
% Requirements Toolbox. Rebuilds requirements/fred_catalog.slreqx from the
% project's own sources, so the requirement text and the checks that verify
% it come from the same files:
%
%   CARD.A01 .. CARD.A17  one per cardinality rule in
%                         neo4j/cypher/fred_degree_audit.cypher (the rule's
%                         comment block becomes the description)
%   MODEL.M01 .. M07      the design model agrees with both DDL files, the
%                         graph model, the live stores and the diagrams
%   GDSS.G01              the naive adapter's fit-payload contract
%
% Each requirement gets a "Verify" link from the test method that checks it
% (tests/unit/DesignModelTest.m, tests/integration/LiveCatalogTest.m,
% tests/unit/NaiveAdapterPayloadTest.m), so the Requirements Editor's
% Traceability Matrix and MATLAB Test's requirements-based testing can show
% which rules are verified, which failed, and which have no test.
%
% The file is regenerated in full: the previous set and its link file are
% deleted first. Edit this function, not the .slreqx.

arguments
    options.ProjectRoot (1,1) string = string(fileparts(fileparts(mfilename("fullpath"))))
    options.OutputFile (1,1) string = fullfile("requirements", "fred_catalog.slreqx")
end

root = options.ProjectRoot;
outFile = fullfile(root, options.OutputFile);
if ~isfolder(fileparts(outFile)), mkdir(fileparts(outFile)); end
addpath(fileparts(outFile));   % links store the set by name, resolved on the path

% start clean: close a loaded copy, remove the old set and link files
for loaded = slreq.find("Type", "ReqSet")
    if string(loaded.Filename) == outFile, close(loaded); end
end
for stale = [outFile, regexprep(outFile, "\.slreqx$", ".slmx")]
    if isfile(stale), delete(stale); end
end

reqSet = slreq.new(outFile);
reqSet.Description = "FRED Metadata Catalog (ADIT2200, Fall 2026). Generated by src/build_fred_requirements.m.";

%% Cardinality rules, from the degree-audit file
auditPath = fullfile(root, "neo4j", "cypher", "fred_degree_audit.cypher");
rules = parseAuditRules(auditPath);

card = add(reqSet, "Id", "CARD", "Type", "Container", ...
    "Summary", "Cardinality: every crow's-foot constraint on the ERD holds in the graph", ...
    "Description", sprintf(['Neo4j Community cannot declare cardinality. Each constraint is a ' ...
    'query in %s whose expected answer is zero rows. Rules A01 to A05 tolerate the ' ...
    'data-list series (dataset_id set).'], "neo4j/cypher/fred_degree_audit.cypher"));

liveTest = fullfile(root, "tests", "integration", "LiveCatalogTest.m");
designTest = fullfile(root, "tests", "unit", "DesignModelTest.m");
gdssTest = fullfile(root, "tests", "unit", "NaiveAdapterPayloadTest.m");

for k = 1:numel(rules)
    r = rules(k);
    req = add(card, "Id", r.id, "Summary", r.summary, "Description", r.description);
    switch r.id
        case {"A01", "A02", "A03", "A04", "A05"}
            method = "seriesRulesFailOnlyForDataListSeries";
        case "A06"
            method = "everyReleaseHasASource";
        otherwise
            method = "structuralCardinalityRulesHold";
    end
    verifyLink(req, liveTest, method);
end

%% Model agreement
model = add(reqSet, "Id", "MODEL", "Type", "Container", ...
    "Summary", "One checked model: diagrams, DDL and live stores never disagree", ...
    "Description", "src/+dbdesign/fred_relational_model.m is the single source; every other representation is compared with it.");

m = { ...
    "M01", "The model matches sql/fred_schema.sql (PostgreSQL)", ...
           "Tables, column order, declared types, NOT NULL, defaults, keys, foreign keys with ON DELETE, CHECK constraints and indexes.", designTest, "modelMatchesPostgresDdl"
    "M02", "The model matches sql/mysql/fred_schema.sql (MySQL/MariaDB)", ...
           "Same comparison for the MySQL dialect.", designTest, "modelMatchesMysqlDdl"
    "M03", "The graph model covers the relational model", ...
           "Every table is a label, a join table turned relationship, or listed as excluded; every foreign key is a relationship or excluded.", designTest, "graphCoversRelationalModel"
    "M04", "The live PostgreSQL catalog matches the model", ...
           "information_schema and pg_catalog agree with the model, including triggers, functions and procedures.", liveTest, "postgresMatchesModel"
    "M05", "The live Neo4j database matches the graph model", ...
           "Labels, property types, relationship patterns, uniqueness constraints and indexes agree with dbdesign.fred_graph_model.", liveTest, "neo4jMatchesGraphModel"
    "M06", "Every diagram names every table, label and relationship it documents", ...
           "The logical, FD-map, table-map, physical and graph views are rendered from the model and compile with Graphviz.", designTest, ["schemaViewNamesEveryTable", "fdViewNamesEveryTable", "graphViewNamesEveryLabelAndRelationship"]
    "M07", "The degree audit names only relationship types the graph model declares", ...
           "Seventeen statements A01..A17 in order, each returning a rule column.", designTest, "degreeAuditCoversEveryRelationshipItNames"};

for k = 1:size(m, 1)
    req = add(model, "Id", m{k, 1}, "Summary", m{k, 2}, "Description", m{k, 3});
    for method = m{k, 5}
        verifyLink(req, m{k, 4}, method);
    end
end

%% MATLAB readers
readTest = fullfile(root, "tests", "integration", "LiveSeriesReaderTest.m");
sqlTest = fullfile(root, "tests", "unit", "SeriesReaderSqlTest.m");
reader = add(reqSet, "Id", "READ", "Type", "Container", ...
    "Summary", "MATLAB reads the catalog with the same as-of semantics as SQL", ...
    "Description", "src/fred_series.m, fred_panel.m, fred_series_sql.m and fred_pg_query.m: the regression-side entry point to PostgreSQL.");
rd = { ...
    "R01", "A vintage read in MATLAB equals value_as_of in SQL", ...
           "For any series, period and vintage date, fred_series(id, Vintage=d) returns the value value_as_of(id, period, d) returns, and every row's real-time window contains d.", readTest, "asOfValueEqualsTheSqlFunction"
    "R02", "Today's read is the set of open real-time windows", ...
           "fred_series(id) and Vintage=""latest"" return one row per period, the rows with realtime_end = 9999-12-31, in date order.", readTest, "currentValuesAreTheOpenWindows"
    "R03", "The first-published read covers every period exactly once", ...
           "Vintage=""first"" returns one row per observation_date with the smallest realtime_start.", readTest, "firstPublishedValuesCoverEveryPeriodOnce"
    "R04", "Series metadata on the timetable comes from the series row", ...
           "Title, units, frequency, seasonal adjustment and release are read from the catalog, not typed by the caller.", readTest, "metadataComesFromTheSeriesRow"
    "R05", "A panel is the outer join of its series on observation date", ...
           "One column per id, union of dates, NaN where a series has no period; frequencies are not reconciled.", readTest, "panelIsTheOuterJoinOfItsSeries"
    "R06", "Only identifiers reach the SQL statement", ...
           "A series id is letters, digits, underscore, dot or hyphen; anything else is refused before any query is built.", sqlTest, "onlyIdentifiersReachTheStatement"};
for k = 1:size(rd, 1)
    req = add(reader, "Id", rd{k, 1}, "Summary", rd{k, 2}, "Description", rd{k, 3});
    verifyLink(req, rd{k, 4}, rd{k, 5});
end

%% GDSS adapter contract
gdss = add(reqSet, "Id", "GDSS", "Type", "Container", ...
    "Summary", "Forecast adapters honour the fit-payload contract");
req = add(gdss, "Id", "G01", ...
    "Summary", "The naive random-walk fit payload carries all six uncertainty fields", ...
    "Description", "parameter_covariance, parameter_standard_error, each with _status and _reference. Regression for commit ab38d13, which spliced two assignments into one line.");
verifyLink(req, gdssTest, "fitPayloadHasEveryUncertaintyField");

save(reqSet);
linkSets = slreq.find("Type", "LinkSet");     % one .slmx next to each test file
for k = 1:numel(linkSets)
    save(linkSets(k));
end
fprintf("Wrote %s: %d requirements, %d links\n", erase(outFile, root + filesep), ...
    numel(find(reqSet)) - 4, countLinks(reqSet));

end


function rules = parseAuditRules(auditPath)
% One struct per "// Axx  <summary>" comment block that precedes a statement.
lines = readlines(auditPath);
rules = struct("id", {}, "summary", {}, "description", {});
k = 1;
while k <= numel(lines)
    tok = regexp(lines(k), "^// (A\d\d)\s+(.*)$", "tokens", "once");
    if isempty(tok), k = k + 1; continue; end
    id = string(tok{1});
    text = strtrim(string(tok{2}));
    k = k + 1;
    while k <= numel(lines) && startsWith(lines(k), "//")
        text = text + " " + strtrim(extractAfter(lines(k), "//"));
        k = k + 1;
    end
    summary = strtrim(extractBefore(text + ".", "."));
    rules(end + 1) = struct("id", id, "summary", summary, "description", text); %#ok<AGROW>
end
% A11, A13, A14 share a comment block with the statement before them; give
% them their own entry from the RETURN rule label so every statement is covered.
text = fileread(auditPath);
tok = regexp(text, "'(A\d\d) ([^']+)'", "tokens");
labels = string(vertcat(tok{:}));          % n-by-2: id, label
for k = 1:size(labels, 1)
    if ~any([rules.id] == labels(k, 1))
        rules(end + 1) = struct("id", labels(k, 1), "summary", labels(k, 2), ...
            "description", "See the statement labelled " + labels(k, 1) + " in the audit file."); %#ok<AGROW>
    end
end
[~, order] = sort([rules.id]);
rules = rules(order);
end


function verifyLink(req, testFile, methodName)
% "Verify" link from the lines of a test method to the requirement.
lines = readlines(testFile);
startLine = find(contains(lines, "function " + methodName + "("), 1);
assert(~isempty(startLine), "build_fred_requirements:NoMethod", ...
    "%s has no method %s", testFile, methodName);
endLine = startLine;
depth = 0;
for k = startLine:numel(lines)
    s = strtrim(lines(k));
    if startsWith(s, "function ") || startsWith(s, "for ") || startsWith(s, "if ") ...
            || startsWith(s, "while ") || startsWith(s, "try") || startsWith(s, "switch ")
        depth = depth + 1;
    elseif s == "end"
        depth = depth - 1;
        if depth == 0, endLine = k; break; end
    end
end
% several requirements can share one test method, so reuse its range
range = slreq.getTextRange(testFile, [startLine, endLine]);
if isempty(range)
    range = slreq.createTextRange(testFile, [startLine, endLine]);
end
link = slreq.createLink(range, req);
assert(~isempty(link), "build_fred_requirements:NoLink", ...
    "Could not link %s lines %d-%d to %s", testFile, startLine, endLine, req.Id);
link.Type = "Verify";
link.Description = methodName;
end


function n = countLinks(reqSet)
n = 0;
reqs = find(reqSet);
for k = 1:numel(reqs)
    n = n + numel(inLinks(reqs(k)));
end
end
