function rollingRun = run_arima_rolling_residual_sweep(runSpec)

arguments
    runSpec (1,1) struct
end

requiredFields = [ ...
    "base_config"
    "arima_p_values"
    "arima_d_values"
    "arima_q_values"
    "initial_train_fraction"
    "forecast_horizon"
    "output_folder"];

assert(all(isfield(runSpec, requiredFields)), ...
    "runSpec is missing one or more required fields.");

assert(isstruct(runSpec.base_config) && isscalar(runSpec.base_config), ...
    "runSpec.base_config must be one scalar struct.");

assert(isnumeric(runSpec.initial_train_fraction) && ...
    isscalar(runSpec.initial_train_fraction) && ...
    isfinite(runSpec.initial_train_fraction) && ...
    runSpec.initial_train_fraction > 0 && ...
    runSpec.initial_train_fraction < 1, ...
    "runSpec.initial_train_fraction must be strictly between 0 and 1.");

assert(isnumeric(runSpec.forecast_horizon) && ...
    isscalar(runSpec.forecast_horizon) && ...
    isfinite(runSpec.forecast_horizon) && ...
    runSpec.forecast_horizon >= 1 && ...
    runSpec.forecast_horizon == floor(runSpec.forecast_horizon), ...
    "runSpec.forecast_horizon must be a positive integer.");

outputFolder = string(runSpec.output_folder);

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

baseConfig = runSpec.base_config;

assert(isfield(baseConfig, "normalized_csv_path"), ...
    "runSpec.base_config.normalized_csv_path is required.");

assert(isfield(baseConfig, "source_member"), ...
    "runSpec.base_config.source_member is required.");

assert(isfield(baseConfig, "series_id"), ...
    "runSpec.base_config.series_id is required.");

assert(isfield(baseConfig, "data_variant"), ...
    "runSpec.base_config.data_variant is required.");

assert(isfield(baseConfig, "target_transform"), ...
    "runSpec.base_config.target_transform is required.");

targetSelector = struct( ...
    "source_member", string(baseConfig.source_member), ...
    "series_id", string(baseConfig.series_id), ...
    "data_variant", string(baseConfig.data_variant), ...
    "target_transform", string(baseConfig.target_transform));

dataVersionReference = "";

if isfield(baseConfig, "data_version_reference")
    dataVersionReference = string(baseConfig.data_version_reference);
end

targetData = gdss.load_normalized_target( ...
    string(baseConfig.normalized_csv_path), ...
    targetSelector, ...
    MissingValuePolicy="reject_nonfinite", ...
    DataVersionReference=dataVersionReference);

observationCount = targetData.observation_count;

firstOrigin = ceil( ...
    runSpec.initial_train_fraction * observationCount);

firstOrigin = max(firstOrigin, 10);

lastOrigin = observationCount - 1;

assert(firstOrigin <= lastOrigin, ...
    "Initial training fraction leaves no valid forecast origin.");

originIndices = (firstOrigin:lastOrigin)';

sweepSpec = struct();

sweepSpec.family = "nonseasonal_arima";
sweepSpec.base_config = baseConfig;

sweepSpec.arima_p_values = runSpec.arima_p_values;
sweepSpec.arima_d_values = runSpec.arima_d_values;
sweepSpec.arima_q_values = runSpec.arima_q_values;

if isfield(runSpec, "maximum_arima_order_sum")
    sweepSpec.maximum_arima_order_sum = ...
        runSpec.maximum_arima_order_sum;
end

if isfield(runSpec, "exclude_all_zero_order")
    sweepSpec.exclude_all_zero_order = ...
        runSpec.exclude_all_zero_order;
else
    sweepSpec.exclude_all_zero_order = true;
end

if isfield(runSpec, "constant_policy")
    sweepSpec.constant_policy = string(runSpec.constant_policy);
else
    sweepSpec.constant_policy = "estimate";
end

modelConfigs = gdss.expand_model_config_sweep(sweepSpec);

for i = 1:numel(modelConfigs)

    modelConfigs(i).forecast_horizon_policy = "fixed";
    modelConfigs(i).maximum_forecast_horizon = ...
        runSpec.forecast_horizon;
end

% A fixed horizon is invalid for late origins because fewer than H observed
% values remain. Run only origins where all requested H residuals exist.
lastFullHorizonOrigin = observationCount - runSpec.forecast_horizon;

originIndices = originIndices( ...
    originIndices <= lastFullHorizonOrigin);

assert(~isempty(originIndices), ...
    "No full-horizon rolling origins remain after applying forecast_horizon.");

rollingSweepRun = run_gdss_rolling_config_sweep( ...
    modelConfigs, originIndices);

leafModelId = strings(0, 1);
leafStructureId = strings(0, 1);

leafP = NaN(0, 1);
leafD = NaN(0, 1);
leafQ = NaN(0, 1);

leafOriginIndex = NaN(0, 1);
leafOriginTime = NaT(0, 1);

leafTrainCount = NaN(0, 1);
leafTrainFraction = NaN(0, 1);

leafHorizon = NaN(0, 1);
leafTargetIndex = NaN(0, 1);
leafTargetTime = NaT(0, 1);

leafActual = NaN(0, 1);
leafForecast = NaN(0, 1);
leafResidual = NaN(0, 1);
leafAbsoluteResidual = NaN(0, 1);
leafSquaredResidual = NaN(0, 1);

leafRunStatus = strings(0, 1);

for originPosition = 1:numel(rollingSweepRun.origin_results)

    originResult = rollingSweepRun.origin_results(originPosition);

    % Keep PARTIAL_COMPLETE origins: one failed ARIMA fit must not discard
    % the residuals of every other model at that origin. Completed models
    % are filtered individually below.
    if isempty(originResult.sweep_run)
        continue
    end

    currentSweep = originResult.sweep_run;

    for modelPosition = 1:numel(currentSweep.results)

        currentResult = currentSweep.results(modelPosition);

        if string(currentResult.status) ~= "COMPLETE"
            continue
        end

        currentConfig = modelConfigs(modelPosition);
        currentEvaluation = currentResult.evaluation_run;
        currentLeaves = currentEvaluation.forecast_leaves;

        leafCount = numel(currentLeaves);

        leafModelId = [leafModelId; ...
            repmat(string(currentConfig.model_id), leafCount, 1)];

        leafStructureId = [leafStructureId; ...
            repmat(string(currentConfig.structure_id), leafCount, 1)];

        leafP = [leafP; repmat(currentConfig.arima_p, leafCount, 1)];
        leafD = [leafD; repmat(currentConfig.arima_d, leafCount, 1)];
        leafQ = [leafQ; repmat(currentConfig.arima_q, leafCount, 1)];

        leafOriginIndex = [leafOriginIndex; ...
            [currentLeaves.origin_index]'];

        leafOriginTime = [leafOriginTime; ...
            [currentLeaves.origin_time]'];

        leafTrainCount = [leafTrainCount; ...
            repmat(currentEvaluation.origin_index, leafCount, 1)];

        leafTrainFraction = [leafTrainFraction; ...
            repmat(currentEvaluation.origin_index / observationCount, ...
            leafCount, 1)];

        leafHorizon = [leafHorizon; [currentLeaves.horizon]'];
        leafTargetIndex = [leafTargetIndex; ...
            [currentLeaves.target_index]'];

        leafTargetTime = [leafTargetTime; ...
            [currentLeaves.target_time]'];

        leafActual = [leafActual; [currentLeaves.actual_value]'];
        leafForecast = [leafForecast; ...
            [currentLeaves.point_forecast]'];

        leafResidual = [leafResidual; ...
            [currentLeaves.forecast_error]'];

        leafAbsoluteResidual = [leafAbsoluteResidual; ...
            [currentLeaves.absolute_error]'];

        leafSquaredResidual = [leafSquaredResidual; ...
            [currentLeaves.squared_error]'];

        leafRunStatus = [leafRunStatus; ...
            repmat(string(currentEvaluation.status), leafCount, 1)];
    end
end

forecastLeaves = table( ...
    leafModelId, ...
    leafStructureId, ...
    leafP, ...
    leafD, ...
    leafQ, ...
    leafOriginIndex, ...
    leafOriginTime, ...
    leafTrainCount, ...
    leafTrainFraction, ...
    leafHorizon, ...
    leafTargetIndex, ...
    leafTargetTime, ...
    leafActual, ...
    leafForecast, ...
    leafResidual, ...
    leafAbsoluteResidual, ...
    leafSquaredResidual, ...
    leafRunStatus, ...
    'VariableNames', { ...
    'model_id', ...
    'structure_id', ...
    'p', ...
    'd', ...
    'q', ...
    'origin_index', ...
    'origin_time', ...
    'training_observation_count', ...
    'training_fraction', ...
    'horizon', ...
    'target_index', ...
    'target_time', ...
    'actual_value', ...
    'point_forecast', ...
    'residual_actual_minus_forecast', ...
    'absolute_residual', ...
    'squared_residual', ...
    'evaluation_status'});

forecastLeaves = sortrows(forecastLeaves, ...
    {'model_id', 'origin_index', 'horizon'});

assert(~isempty(forecastLeaves), ...
    "Rolling run produced no completed forecast leaves.");

uniqueModelIds = unique(forecastLeaves.model_id, "stable");

scoreModelId = strings(numel(uniqueModelIds), 1);

scoreP = NaN(numel(uniqueModelIds), 1);
scoreD = NaN(numel(uniqueModelIds), 1);
scoreQ = NaN(numel(uniqueModelIds), 1);

scoreLeafCount = NaN(numel(uniqueModelIds), 1);
scoreOriginCount = NaN(numel(uniqueModelIds), 1);

scoreMeanError = NaN(numel(uniqueModelIds), 1);
scoreMAE = NaN(numel(uniqueModelIds), 1);
scoreRMSE = NaN(numel(uniqueModelIds), 1);

scoreUnderforecastCount = NaN(numel(uniqueModelIds), 1);
scoreOverforecastCount = NaN(numel(uniqueModelIds), 1);
scoreExactForecastCount = NaN(numel(uniqueModelIds), 1);

scoreH1LeafCount = NaN(numel(uniqueModelIds), 1);
scoreH1MAE = NaN(numel(uniqueModelIds), 1);
scoreH1RMSE = NaN(numel(uniqueModelIds), 1);

for modelPosition = 1:numel(uniqueModelIds)

    currentModelId = uniqueModelIds(modelPosition);

    mask = forecastLeaves.model_id == currentModelId;
    leavesForModel = forecastLeaves(mask, :);

    h1Mask = leavesForModel.horizon == 1;
    h1Leaves = leavesForModel(h1Mask, :);

    scoreModelId(modelPosition) = currentModelId;

    scoreP(modelPosition) = leavesForModel.p(1);
    scoreD(modelPosition) = leavesForModel.d(1);
    scoreQ(modelPosition) = leavesForModel.q(1);

    scoreLeafCount(modelPosition) = height(leavesForModel);
    scoreOriginCount(modelPosition) = ...
        numel(unique(leavesForModel.origin_index));

    scoreMeanError(modelPosition) = ...
        mean(leavesForModel.residual_actual_minus_forecast);

    scoreMAE(modelPosition) = ...
        mean(leavesForModel.absolute_residual);

    scoreRMSE(modelPosition) = sqrt( ...
        mean(leavesForModel.squared_residual));

    scoreUnderforecastCount(modelPosition) = sum( ...
        leavesForModel.residual_actual_minus_forecast > 0);

    scoreOverforecastCount(modelPosition) = sum( ...
        leavesForModel.residual_actual_minus_forecast < 0);

    scoreExactForecastCount(modelPosition) = sum( ...
        leavesForModel.residual_actual_minus_forecast == 0);

    scoreH1LeafCount(modelPosition) = height(h1Leaves);

    scoreH1MAE(modelPosition) = ...
        mean(h1Leaves.absolute_residual);

    scoreH1RMSE(modelPosition) = sqrt( ...
        mean(h1Leaves.squared_residual));
end

modelScorecard = table( ...
    scoreModelId, ...
    scoreP, ...
    scoreD, ...
    scoreQ, ...
    scoreLeafCount, ...
    scoreOriginCount, ...
    scoreMeanError, ...
    scoreMAE, ...
    scoreRMSE, ...
    scoreUnderforecastCount, ...
    scoreOverforecastCount, ...
    scoreExactForecastCount, ...
    scoreH1LeafCount, ...
    scoreH1MAE, ...
    scoreH1RMSE, ...
    'VariableNames', { ...
    'model_id', ...
    'p', ...
    'd', ...
    'q', ...
    'retained_residual_count', ...
    'origin_count', ...
    'mean_error_all_leaves', ...
    'mae_all_leaves', ...
    'rmse_all_leaves', ...
    'underforecast_count_all_leaves', ...
    'overforecast_count_all_leaves', ...
    'exact_forecast_count_all_leaves', ...
    'one_step_residual_count', ...
    'one_step_mae', ...
    'one_step_rmse'});

modelScorecard = sortrows(modelScorecard, ...
    {'one_step_rmse', 'one_step_mae'}, ...
    {'ascend', 'ascend'});

outputPrefix = string(baseConfig.series_id);

forecastLeavesPath = fullfile(outputFolder, ...
    outputPrefix + "_arima_rolling_forecast_leaves.csv");

modelScorecardPath = fullfile(outputFolder, ...
    outputPrefix + "_arima_rolling_model_scorecard.csv");

writetable(forecastLeaves, forecastLeavesPath);
writetable(modelScorecard, modelScorecardPath);

rollingRun = struct();

rollingRun.record_type = "ARIMA_ROLLING_RESIDUAL_SWEEP";
rollingRun.status = string(rollingSweepRun.status);

rollingRun.series_id = string(baseConfig.series_id);
rollingRun.data_variant = string(baseConfig.data_variant);
rollingRun.target_transform = string(baseConfig.target_transform);

rollingRun.observation_count = observationCount;
rollingRun.initial_train_fraction = runSpec.initial_train_fraction;
rollingRun.first_origin_index = originIndices(1);
rollingRun.last_origin_index = originIndices(end);
rollingRun.origin_count = numel(originIndices);

rollingRun.forecast_horizon = runSpec.forecast_horizon;
rollingRun.model_count = numel(modelConfigs);

rollingRun.model_configs = modelConfigs;
rollingRun.forecast_leaves = forecastLeaves;
rollingRun.model_scorecard = modelScorecard;

rollingRun.forecast_leaves_csv = forecastLeavesPath;
rollingRun.model_scorecard_csv = modelScorecardPath;

rollingRun.rolling_sweep_run = rollingSweepRun;

end