function originIndices = create_origin_grid(originSpec)

arguments
    originSpec (1,1) struct
end

assert(isfield(originSpec, "first_origin_index"), ...
    "originSpec.first_origin_index is required.");

assert(isfield(originSpec, "last_origin_index"), ...
    "originSpec.last_origin_index is required.");

assert(isfield(originSpec, "origin_step"), ...
    "originSpec.origin_step is required.");

firstOriginIndex = originSpec.first_origin_index;
lastOriginIndex = originSpec.last_origin_index;
originStep = originSpec.origin_step;

assert(isnumeric(firstOriginIndex) && ...
    isscalar(firstOriginIndex) && ...
    isfinite(firstOriginIndex) && ...
    firstOriginIndex >= 1 && ...
    firstOriginIndex == floor(firstOriginIndex), ...
    "originSpec.first_origin_index must be one positive integer.");

assert(isnumeric(lastOriginIndex) && ...
    isscalar(lastOriginIndex) && ...
    isfinite(lastOriginIndex) && ...
    lastOriginIndex >= firstOriginIndex && ...
    lastOriginIndex == floor(lastOriginIndex), ...
    "originSpec.last_origin_index must be one positive integer " + ...
    "greater than or equal to first_origin_index.");

assert(isnumeric(originStep) && ...
    isscalar(originStep) && ...
    isfinite(originStep) && ...
    originStep >= 1 && ...
    originStep == floor(originStep), ...
    "originSpec.origin_step must be one positive integer.");

originIndices = ( ...
    firstOriginIndex:originStep:lastOriginIndex)';

assert(~isempty(originIndices), ...
    "Origin grid must contain at least one origin index.");

end